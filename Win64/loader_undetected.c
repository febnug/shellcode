// Deobfuscate an XOR'd string into a stack buffer
void deobf(char* dst, const char* src) {
    while (*src) {
        *dst = *src ^ 0x9D;
        dst++; src++;
    }
    *dst = 0;
}

// Rolling XOR decrypt (different from simple XOR to break signatures)
void decrypt(BYTE* buf, int len) {
    BYTE key = 0xAA;
    for (int i = 0; i < len; i++) {
        BYTE k = key;
        key = (key * 7 + 11) & 0xFF;  // rolling key
        buf[i] ^= k;
    }
}

