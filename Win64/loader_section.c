// Compile: x86_64-w64-mingw32-gcc -O2 -o loader.exe loader_section.c -s -Wall -fno-ident
//
// Uses: NtCreateSection + NtMapViewOfSection + memcpy + NtClose
// No:  VirtualAlloc, VirtualProtect, CreateThread, PEB walking, function pointer cast
